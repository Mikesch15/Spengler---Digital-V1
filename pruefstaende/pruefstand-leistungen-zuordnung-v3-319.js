p(s2.leiPositionFinden(L,{angebot_id:1,angebot_position:"2",angebot_position_beschreibung:"Blech B"}).status==="mehrdeutig","ohne Beschreibungs-Verfeinerung waere es mehrdeutig (Test greift)");
m=q.slice(a,b).replace('if(l.angebot_id)return "Offerte-Pos. "+(nr||"ohne Nummer");','if(l.angebot_id&&nr)return "Offerte-Pos. "+nr;');
s2=laden(m);
p(s2.leiHerkunftText({angebot_id:5,angebot_position:""})==="Zusatzleistung","Mutation (alte Logik) wuerde Offerte-Position als Zusatzleistung zeigen (Test greift)");
m=q.slice(a,b).replace('!g.has(x)','false');
s2=laden(m);
p(s2.leiVerknuepfungsDiff([1],[2]).weg.length===0,"Mutation Diff erkannt");
console.log("\nErgebnis: "+ok+" ok, "+fail+" fehlgeschlagen");
process.exit(fail?1:0);
