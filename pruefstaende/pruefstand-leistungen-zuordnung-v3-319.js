"use strict";
const fs=require("fs"), path=require("path"), vm=require("vm");
let ok=0,fail=0;
const p=(b,t,z)=>{if(b){ok++;console.log("  ok  "+t)}else{fail++;console.log("  FEHLGESCHLAGEN: "+t+(z!==undefined?"  "+JSON.stringify(z).slice(0,300):""))}};
const w=process.cwd();
const q=fs.readFileSync(path.join(w,"js/65-leistungen.js"),"utf8");
const q70=fs.readFileSync(path.join(w,"js/70-ansicht2.js"),"utf8");
const a=q.indexOf("function leiBeschrKurz"), b=q.indexOf("// ---- Ende Hilfsfunktionen");
p(a>0&&b>a,"Hilfsfunktionen stehen in js/65",[a,b]);
function laden(code){const s={};vm.runInNewContext(code,s);return s}
const sb=laden(q.slice(a,b));
const L=[{angebotId:1,pos:"1",description:"Rinne"},{angebotId:1,pos:"2",description:"Blech A"},{angebotId:1,pos:"2",description:"Blech B"},{angebotId:1,pos:"",description:"Ohne Nr"},{angebotId:2,pos:"1",description:"Andere Offerte"}];
console.log("\nA · Position finden");
p(sb.leiPositionFinden(L,{angebot_id:1,angebot_position:"1"}).index===0,"normale Position wird gefunden");
p(sb.leiPositionFinden(L,{angebot_id:2,angebot_position:"1"}).index===4,"gleiche Nummer in anderer Offerte -> richtige Offerte");
p(sb.leiPositionFinden(L,{angebot_id:1,angebot_position:"2"}).status==="mehrdeutig","gleiche Nummer ohne Beschreibung -> mehrdeutig (nicht raten)");
p(sb.leiPositionFinden(L,{angebot_id:1,angebot_position:"2",angebot_position_beschreibung:"Blech B"}).index===2,"gleiche Nummer + Beschreibung -> genau die richtige");
p(sb.leiPositionFinden(L,{angebot_id:1,angebot_position:"",angebot_position_beschreibung:""}).index===3,"Position ohne Nummer wird gefunden");
p(sb.leiPositionFinden(L,{angebot_id:1,angebot_position:"9"}).status==="fehlt","unbekannte Position -> fehlt");
p(sb.leiPositionFinden(L,{angebot_id:null,angebot_position:"1"}).status==="keine","ohne Offerte -> keine");
p(sb.leiPositionFinden(L,null).status==="keine","null -> keine");
p(sb.leiPositionFinden(null,{angebot_id:1,angebot_position:"1"}).status==="fehlt","keine Liste -> fehlt, kein Absturz");
console.log("\nB · Herkunft");
p(sb.leiHerkunftText({angebot_id:5,angebot_position:"3"})==="Offerte-Pos. 3","mit Offerte");
p(/ohne Nummer/.test(sb.leiHerkunftText({angebot_id:5,angebot_position:""})),"Offerte ohne Nummer ist KEINE Zusatzleistung");
p(sb.leiHerkunftText({angebot_id:null,angebot_position:null})==="Zusatzleistung","echte Zusatzleistung");
p(/Offerte gelöscht.*Pos\. 4/.test(sb.leiHerkunftText({angebot_id:null,angebot_position:"4"})),"geloeschte Offerte ehrlich benannt");
p(sb.leiHerkunftText(null)==="Zusatzleistung","null -> Zusatzleistung");
console.log("\nC · Verknuepfungs-Diff (idempotent)");
let d=sb.leiVerknuepfungsDiff([1,2],[2,3]);
p(JSON.stringify(d)==='{"neu":[3],"weg":[1]}',"nur Unterschied",d);
d=sb.leiVerknuepfungsDiff([1,2],[1,2]);
p(!d.neu.length&&!d.weg.length,"erneutes Speichern aendert nichts");
d=sb.leiVerknuepfungsDiff(["1"],[1]);
p(!d.neu.length&&!d.weg.length,"Text-/Zahl-IDs werden gleich behandelt");
d=sb.leiVerknuepfungsDiff(null,[7,7]);
p(JSON.stringify(d)==='{"neu":[7],"weg":[]}',"doppelte Auswahl -> einmal",d);
console.log("\nD · Quelltext");
p(/angebot_position_beschreibung/.test(q),"Beschreibung wird gespeichert");
p(/behalten/.test(q),"bisherige Zuordnung wird beibehalten, wenn nicht eindeutig");
p(/ignoreDuplicates/.test(q),"Verknuepfen per upsert ohne Duplikate");
p(!/from\("leistung_massaufnahmen"\)\.delete\(\)\.eq\("leistung_id",[^)]*\)\s*;/.test(q)&&/delete\(\)\.eq\("leistung_id",leistungId\)\.in\("measurement_id"/.test(q),"kein 'alles loeschen, dann neu' mehr");
p(/leiVerknuepfungsDiff\(/.test(q.slice(b)),"Speichern nutzt den Diff");
p(/dbFehlerText/.test(q),"Fehler ueber dbFehlerText");
p(/leiHerkunftText\(l\)/.test(q70),"Cockpit (js/70) nutzt dieselbe Herkunft");
p(/keiner Leistung zugeordnet/.test(q)&&/in Ordnung/.test(q),"nicht zugeordnete Massaufnahmen: Hinweis, keine Zwangszuordnung");
console.log("\nE · Gegenproben");
let m=q.slice(a,b).replace('kand.length>1','kand.length>99');
