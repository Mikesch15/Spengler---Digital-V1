-- v3.425: Profile aus der App an das Fusion-Add-in «Spengler Digital CAD» senden (Länge, Stück).
-- Rein additiv: eine neue Tabelle, nichts Bestehendes wird veraendert.
-- Die App schreibt (Knopf «An CAD senden» an einer Massaufnahme «Freies Profil»), das Add-in liest die offenen Eintraege
-- zum Auftrag, baut das Blech und setzt den Status auf «gebaut». `daten` ist eine Kopie der Schenkel zum Sendezeitpunkt –
-- spaetere Aenderungen an der Massaufnahme veraendern einen schon gesendeten Auftrag nicht.
-- Zugriff wie bei den Projekten: Recht «projects» (ansehen/bearbeiten) plus die RESTRICTIVE Firmengrenze.
create table if not exists public.cad_profil_auftraege (
  id             bigint generated by default as identity primary key,
  company_id     uuid not null default my_company_id() references public.companies(id) on delete cascade,
  project_id     bigint not null references public.projects(id) on delete cascade,
  measurement_id bigint references public.measurements(id) on delete set null,
  titel          text not null default '',
  laenge_mm      numeric not null check (laenge_mm > 0 and laenge_mm <= 100000),
  stueck         integer not null default 1 check (stueck >= 1 and stueck <= 999),
  staerke_mm     numeric,
  daten          jsonb not null default '{}'::jsonb,
  notiz          text not null default '',
  status         text not null default 'offen' check (status in ('offen','gebaut','storniert')),
  gebaut_am      timestamptz,
  erstellt_von   uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists cad_profil_auftraege_projekt_idx on public.cad_profil_auftraege (company_id, project_id, status);

alter table public.cad_profil_auftraege enable row level security;

drop policy if exists cad_profil_auftraege_select_permission on public.cad_profil_auftraege;
create policy cad_profil_auftraege_select_permission on public.cad_profil_auftraege for select using (has_permission('projects','view'));
drop policy if exists cad_profil_auftraege_insert_permission on public.cad_profil_auftraege;
create policy cad_profil_auftraege_insert_permission on public.cad_profil_auftraege for insert with check (has_permission('projects','edit'));
drop policy if exists cad_profil_auftraege_update_permission on public.cad_profil_auftraege;
create policy cad_profil_auftraege_update_permission on public.cad_profil_auftraege for update using (has_permission('projects','edit')) with check (has_permission('projects','edit'));
drop policy if exists cad_profil_auftraege_delete_permission on public.cad_profil_auftraege;
create policy cad_profil_auftraege_delete_permission on public.cad_profil_auftraege for delete using (has_permission('projects','edit'));

drop policy if exists tenant_boundary_cad_profil_auftraege on public.cad_profil_auftraege;
create policy tenant_boundary_cad_profil_auftraege on public.cad_profil_auftraege as restrictive for all
  using (company_id = my_company_id())
  with check (company_id = my_company_id() and exists (
    select 1 from public.projects p where p.id = cad_profil_auftraege.project_id and p.company_id = my_company_id()));

revoke all on public.cad_profil_auftraege from anon;
