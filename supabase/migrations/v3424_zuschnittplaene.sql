-- v3.424: Zuschnittplaene aus dem Zuschnittrechner (js/105) unter einem Projekt ablegen.
-- Rein additiv: eine neue Tabelle, nichts Bestehendes wird veraendert.
-- Muster wie `abwicklungen`: Zugriff ueber Recht «materials» (ansehen/bearbeiten),
-- dazu die RESTRICTIVE Firmengrenze (company_id + Projekt gehoert zur eigenen Firma).
create table if not exists public.zuschnittplaene (
  id            bigint generated by default as identity primary key,
  company_id    uuid not null default my_company_id() references public.companies(id) on delete cascade,
  project_id    bigint references public.projects(id) on delete set null,
  bezeichnung   text not null default '',
  eingaben      jsonb not null default '{}'::jsonb,   -- Format, Zuschnittmasse (mit Positionen), Optionen
  ergebnis      jsonb not null default '{}'::jsonb,   -- der gerechnete Plan (Tafeln/Abschnitte, Lage, Schnittfolge)
  erstellt_von  uuid references public.profiles(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists zuschnittplaene_firma_idx   on public.zuschnittplaene (company_id, created_at desc);
create index if not exists zuschnittplaene_projekt_idx on public.zuschnittplaene (project_id);

alter table public.zuschnittplaene enable row level security;

drop policy if exists zuschnittplaene_select_permission on public.zuschnittplaene;
create policy zuschnittplaene_select_permission on public.zuschnittplaene for select using (has_permission('materials','view'));
drop policy if exists zuschnittplaene_insert_permission on public.zuschnittplaene;
create policy zuschnittplaene_insert_permission on public.zuschnittplaene for insert with check (has_permission('materials','edit'));
drop policy if exists zuschnittplaene_update_permission on public.zuschnittplaene;
create policy zuschnittplaene_update_permission on public.zuschnittplaene for update using (has_permission('materials','edit')) with check (has_permission('materials','edit'));
drop policy if exists zuschnittplaene_delete_permission on public.zuschnittplaene;
create policy zuschnittplaene_delete_permission on public.zuschnittplaene for delete using (has_permission('materials','edit'));

drop policy if exists tenant_boundary_zuschnittplaene on public.zuschnittplaene;
create policy tenant_boundary_zuschnittplaene on public.zuschnittplaene as restrictive for all
  using (company_id = my_company_id())
  with check (company_id = my_company_id() and (project_id is null or exists (
    select 1 from public.projects p where p.id = zuschnittplaene.project_id and p.company_id = my_company_id())));

-- Kein Zugriff fuer nicht angemeldete Besucher (die Policies verlangen ohnehin eine Anmeldung).
revoke all on public.zuschnittplaene from anon;
